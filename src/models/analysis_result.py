# Import third party packages.
import pandas as pd
from pydantic import BaseModel, ConfigDict

# Import local packages.
from src.models.backtest_result import BacktestResult
from src.models.signal import Signal
from src.models.statistics import Statistics
from src.models.financial_statements import FinancialStatements
from src.models.fundamentals import Fundamentals


class AnalysisResult(BaseModel):
    """
    Represents the complete output generated by a stock analysis operation.

    Attributes:
        ticker: Stock ticker symbol associated with the analysis.
        raw_data: Historical market data retrieved for the analyzed asset.
        indicators: Calculated technical indicators and derived metrics based on the historical market data.
        signals: List of trading signals generated by the analysis strategy.
        statistics: Summary price statistics and performance metrics for the analyzed period.
        fundamentals: Company fundamental information and valuation metrics, if requested.
        financial_statements: Structured financial statement data including income statement, balance sheet, and cash flow statement information, if requested.
        backtest_result: Results and performance metrics from the backtesting simulation, if performed.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    ticker: str
    raw_data: pd.DataFrame
    indicators: pd.DataFrame
    signals: list[Signal]
    statistics: Statistics
    fundamentals: Fundamentals | None = None
    financial_statements: FinancialStatements | None = None
    backtest_result: BacktestResult | None = None
